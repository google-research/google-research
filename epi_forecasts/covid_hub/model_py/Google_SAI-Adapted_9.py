class InlaModelWrapper:
  """Encapsulates R-INLA setup, spatial graph definition, and model fitting.

  Implemented as a singleton to avoid re-initializing instance attributes and
  leveraging a global mechanism for the R environment setup to ensure it happens
  only once per kernel session, irrespective of cell re-execution.
  """

  _instance = None  # Singleton instance

  def __new__(cls, *args, **kwargs):
    if cls._instance is None:
      cls._instance = super(InlaModelWrapper, cls).__new__(cls)
    return cls._instance

  def __init__(self, locations_df):
    # This __init__ logic runs every time InlaModelWrapper() is called,
    # but the R environment setup itself (_setup_r_environment_once)
    # is guaranteed to run only once per kernel session.
    # So, we just populate the instance attributes from the global _R_OBJECTS.

    self.rpy2_available = False
    self.r_robjects = None
    self.r_pandas2ri = None
    self.r_base = None
    self.r_stats = None
    self.r_utils = None
    self.r_INLA = None
    self.r_graph_obj = None
    self.location_fips_to_id: Dict[int, int] = {}
    self.num_full_locations = 0

    # Attempt global R environment setup via the dedicated function
    env_setup_success = _setup_r_environment_once(locations_df)

    if env_setup_success:
      self.rpy2_available = True
      # Populate instance attributes from the globally stored R objects
      # Use .get() for robustness against partial _R_OBJECTS state
      self.r_robjects = _R_OBJECTS.get('r_robjects')
      self.r_pandas2ri = _R_OBJECTS.get('r_pandas2ri')
      self.r_base = _R_OBJECTS.get('r_base')
      self.r_stats = _R_OBJECTS.get('r_stats')
      self.r_utils = _R_OBJECTS.get('r_utils')
      self.r_INLA = _R_OBJECTS.get('r_INLA')
      self.r_graph_obj = _R_OBJECTS.get('r_graph_obj')
      self.location_fips_to_id = _R_OBJECTS.get('location_fips_to_id', {})
      self.num_full_locations = _R_OBJECTS.get('num_full_locations', 0)
    # No additional warnings here if setup failed; _setup_r_environment_once handles the initial warning.

  def _improved_fallback_predict(
      self,
      train_x,
      train_y,
      test_x,
      quantiles,
  ):
    """Provides an improved fallback prediction when R-INLA is not available.

    This attempts to predict based on the last observed value for each location
    by drawing samples from a Negative Binomial distribution, providing a more
    statistically sound probabilistic forecast than a simple linear spread.
    """
    warnings.warn(
        'R-INLA is not available or failed to initialize. '
        'Using improved fallback predictions.',
        UserWarning,
    )

    train_combined = train_x.copy()
    train_combined[TARGET_STR] = train_y

    train_combined['target_end_date'] = pd.to_datetime(
        train_combined['target_end_date']
    )

    last_observed_data = (
        train_combined.groupby('location')
        .apply(lambda x: x.loc[x['target_end_date'].idxmax()])
        .reset_index(drop=True)[['location', TARGET_STR]]
    )
    last_observed_data = last_observed_data.set_index('location')[TARGET_STR]

    predicted_quantiles_df = pd.DataFrame(index=test_x.index)

    fallback_dispersion_param = (
        10.0  # Default dispersion parameter for Negative Binomial
    )

    all_predicted_samples = np.zeros((len(test_x), N_SAMPLES))

    for i, (idx, row) in enumerate(test_x.iterrows()):
      location = row['location']

      last_val_mean = last_observed_data.get(
          location, 1.0
      )  # Default to 1.0 if no prior data for NegBin
      if last_val_mean <= 0:
        last_val_mean = 1.0  # Ensure positive mean for Negative Binomial

      # Calculate 'p' parameter for Negative Binomial consistent with R's rnbinom(size, mu) and scipy.stats.nbinom(n, p)
      # R: mean = mu, size = r.  scipy: mean = n*(1-p)/p, where n is 'size' from R.
      # So for scipy, p = n / (n + mu)
      p_param = fallback_dispersion_param / (
          last_val_mean + fallback_dispersion_param
      )
      p_param = np.clip(
          p_param, 1e-6, 1.0 - 1e-6
      )  # Ensure p is valid and not exactly 1

      samples_for_row = scipy.stats.nbinom.rvs(
          n=fallback_dispersion_param,  # This is 'r' or 'size' in R, or 'n' in scipy docs
          p=p_param,
          size=N_SAMPLES,
      )
      all_predicted_samples[i, :] = samples_for_row

    for q in quantiles:
      predicted_quantiles_df[f'quantile_{q}'] = np.quantile(
          all_predicted_samples, q, axis=1
      )

    predicted_quantiles_df.loc[:, :] = np.sort(
        predicted_quantiles_df.values, axis=1
    )
    predicted_quantiles_df.loc[:, :] = np.maximum(
        0, predicted_quantiles_df.values
    )
    return predicted_quantiles_df.round().astype(int)

  def predict(
      self,
      train_x,
      train_y,
      test_x,
      quantiles,
      n_samples,
  ):
    """Performs the actual INLA model fitting and prediction using the

    pre-initialized rpy2 environment and spatial graph.
    """
    # Centralized check for INLA availability
    if not self.rpy2_available:
      return self._improved_fallback_predict(
          train_x, train_y, test_x, quantiles
      )

    # Additional check for critical rpy2 objects after rpy2_available is true
    # This can happen if INLA was installed but some core rpy2 imports/assignments failed later
    if not all([
        self.r_robjects,
        self.r_pandas2ri,
        self.r_base,
        self.r_stats,
        self.r_utils,
        self.r_INLA,
    ]):
      return self._improved_fallback_predict(
          train_x, train_y, test_x, quantiles
      )

    # --- Data Preprocessing ---
    train_x = train_x.copy()
    test_x = test_x.copy()
    train_x['target_end_date'] = pd.to_datetime(train_x['target_end_date'])
    test_x['target_end_date'] = pd.to_datetime(test_x['target_end_date'])

    train_df = train_x.assign(y=train_y)
    test_df = test_x.assign(y=np.nan)

    combined_df = pd.concat(
        [
            train_df[['target_end_date', 'location', 'population', 'y']],
            test_df[['target_end_date', 'location', 'population', 'y']],
        ],
        ignore_index=True,
    )

    combined_df = combined_df.sort_values(
        by=['location', 'target_end_date']
    ).reset_index(drop=True)

    # Handle zero population by replacing with 1 to avoid log(0) and potential division issues
    combined_df['log_population'] = np.log(
        combined_df['population'].replace(0, 1)
    )

    combined_df['location_id'] = combined_df['location'].map(
        self.location_fips_to_id
    )
    if combined_df['location_id'].isnull().any():
      warnings.warn(
          'Some locations in current data are not found in the pre-computed'
          ' FIPS ID mapping. Falling back to improved dummy predictions for'
          ' this call.',
          UserWarning,
      )
      return self._improved_fallback_predict(
          train_x, train_y, test_x, quantiles
      )

    all_dates = sorted(combined_df['target_end_date'].unique())
    date_to_time_id = {date: i + 1 for i, date in enumerate(all_dates)}
    combined_df['time_id'] = combined_df['target_end_date'].map(date_to_time_id)

    combined_df['week_of_year'] = (
        combined_df['target_end_date'].dt.isocalendar().week.astype(int)
    )
    combined_df['sin_week'] = np.sin(
        2 * np.pi * combined_df['week_of_year'] / 52
    )
    combined_df['cos_week'] = np.cos(
        2 * np.pi * combined_df['week_of_year'] / 52
    )

    test_indices_in_combined = combined_df[
        combined_df['y'].isna()
    ].index.tolist()

    # --- Model Specification & Bayesian Inference ---
    try:
      combined_df_r = self.r_pandas2ri.py2rpy(combined_df)
    except Exception as e:
      warnings.warn(
          'Failed to convert DataFrame to R object for INLA (Error during'
          f' py2rpy conversion): {e}. Falling back to improved dummy'
          ' predictions for this call.',
          UserWarning,
      )
      return self._improved_fallback_predict(
          train_x, train_y, test_x, quantiles
      )

    formula_str = (
        'y ~ 1 + offset(log_population) + sin_week + cos_week + '
        "f(time_id, model = 'rw1', constr = TRUE) + "
        "f(location_id, model = 'bym', graph = g, constr = TRUE)"
    )
    r_formula = self.r_robjects.r(f"as.formula('{formula_str}')")

    # Assign graph 'g' to R global environment for the INLA formula to find it
    self.r_robjects.globalenv['g'] = self.r_graph_obj
    model = None  # Initialize model to None, in case fitting fails

    try:
      # Use r_robjects.r.list for control parameters for robustness
      control_predictor_list = self.r_robjects.r.list(compute=True)
      control_inla_list = self.r_robjects.r.list(int_strategy='auto')

      model = self.r_INLA.inla(
          r_formula,
          data=combined_df_r,
          family='nbinomial',
          control_predictor=control_predictor_list,
          control_inla=control_inla_list,
          num_threads=self.r_robjects.IntVector([1]),  # Explicit R integer type
          verbose=self.r_robjects.BoolVector(
              [False]
          ),  # Explicit R boolean type
      )
    except (
        _R_RUNTIME_ERROR_TYPE
    ) as e:  # Use potentially updated _R_RUNTIME_ERROR_TYPE
      warnings.warn(
          f'R-INLA model fitting failed for this fold (RRuntimeError): {e}. '
          'Falling back to improved dummy predictions for this call.',
          UserWarning,
      )
      return self._improved_fallback_predict(
          train_x, train_y, test_x, quantiles
      )
    except Exception as e:
      warnings.warn(
          f'R-INLA model fitting failed for this fold (General Error): {e}. '
          'Falling back to improved dummy predictions for this call.',
          UserWarning,
      )
      return self._improved_fallback_predict(
          train_x, train_y, test_x, quantiles
      )
    finally:
      # Crucially, remove 'g' from R global environment to avoid polluting it or
      # causing issues in subsequent calls if 'g' changes.
      if 'g' in self.r_robjects.globalenv:
        self.r_robjects.r(
            'rm(g, envir = .GlobalEnv)'
        )  # Use R's rm function for R cleanup

    # If model fitting failed (e.g., due to a non-RRuntimeError caught by generic Exception)
    if model is None:
      return self._improved_fallback_predict(
          train_x, train_y, test_x, quantiles
      )

    # --- Sampling ---
    try:
      samples = self.r_INLA.inla_posterior_sample(n_samples, model)

      # Extract dispersion parameter 'size' for the nbinomial likelihood
      # For INLA's nbinomial, the `size` parameter corresponds to `r` in the R `rnbinom(n, size, mu)` function,
      # where mean = mu and variance = mu^2/size.
      hyper_samples_r = self.r_robjects.r(f"""
                vapply(samples, function(x) x$hyperpar['size for the nbinomial likelihood'], FUN.VALUE = numeric(1))
            """)
      hyper_samples_py = np.array(hyper_samples_r)

      # Extract linear predictor (eta) samples
      eta_samples_r = self.r_robjects.r(f"""
                do.call(cbind, lapply(samples, function(x) x$latent['Predictor', ]))
            """)
      eta_samples_py = np.array(eta_samples_r)
    except Exception as e:
      warnings.warn(
          f'R-INLA posterior sampling failed for this fold: {e}. '
          'Falling back to improved dummy predictions for this call.',
          UserWarning,
      )
      return self._improved_fallback_predict(
          train_x, train_y, test_x, quantiles
      )

    # --- Forecast Construction ---
    num_test_rows = len(test_indices_in_combined)

    # Select the eta (linear predictor) values corresponding to the test observations
    eta_for_test_obs = eta_samples_py[test_indices_in_combined, :]
    # Apply inverse link function (exp) to get mean (mu)
    mu_for_test_obs = np.exp(eta_for_test_obs)

    try:
      # Need to match the dimensions for rnbinom: size (r) and mu (mean) should be provided for each sample-observation pair
      mu_flat_r = self.r_robjects.FloatVector(mu_for_test_obs.flatten())
      # Repeat hyper_samples_py for each test row to match mu_flat_r length
      size_repeated_r = self.r_robjects.FloatVector(
          np.tile(hyper_samples_py, num_test_rows)
      )

      # Draw samples from Negative Binomial distribution using R's rnbinom
      # n = total number of random variates to generate
      # size = dispersion parameter (r)
      # mu = mean parameter
      predicted_draws_r = self.r_stats.rnbinom(
          n=len(mu_flat_r), size=size_repeated_r, mu=mu_flat_r
      )
      predicted_samples_flat = np.array(predicted_draws_r)
      predicted_samples = predicted_samples_flat.reshape(
          num_test_rows, n_samples
      )
    except Exception as e:
      warnings.warn(
          f'Failed to draw Negative Binomial samples from R for this fold: {e}.'
          ' Falling back to improved dummy predictions for this call.',
          UserWarning,
      )
      return self._improved_fallback_predict(
          train_x, train_y, test_x, quantiles
      )

    test_y_hat_quantiles = pd.DataFrame(index=test_x.index)
    for q in quantiles:
      test_y_hat_quantiles[f'quantile_{q}'] = np.quantile(
          predicted_samples, q, axis=1
      )

    # Ensure monotonicity and non-negativity
    test_y_hat_quantiles.loc[:, :] = np.sort(
        test_y_hat_quantiles.values, axis=1
    )
    test_y_hat_quantiles.loc[:, :] = np.maximum(0, test_y_hat_quantiles.values)
    test_y_hat_quantiles = test_y_hat_quantiles.round().astype(int)

    return test_y_hat_quantiles


